#!/usr/bin/env python3
"""Write cb_params_table.h for cb_main.c from the generated GRT sources.

Usage: gen_param_table.py <code_dir> <outputs.txt> <out_header>

Every ExportedGlobal per-run parameter (``extern real_T CB_name;`` or
``extern real_T CB_name[N];`` in the generated headers) becomes one table entry,
so the runner can set it by name. outputs.txt holds the expanded root-output
column names (one per line, written by cb_build.m); their count is CB_NY.
"""
import pathlib
import re
import sys

code_dir, outputs_txt, out_header = map(pathlib.Path, sys.argv[1:4])
pat = re.compile(r"^\s*extern\s+real_T\s+(CB_\w+)\s*(?:\[(\d+)\])?\s*;", re.M)
params = {}
for h in sorted(code_dir.rglob("*.h")):
    for name, n in pat.findall(h.read_text(errors="replace")):
        params[name] = int(n) if n else 1
if not params:
    sys.exit("gen_param_table: no CB_* globals found under %s" % code_dir)
names = [ln.strip() for ln in outputs_txt.read_text().splitlines() if ln.strip()]
lines = [
    "/* generated by gen_param_table.py - do not edit */",
    "#ifndef CB_PARAMS_TABLE_H", "#define CB_PARAMS_TABLE_H",
    "typedef struct { const char *name; double *addr; int numel; } cb_param_t;",
    "#define CB_NPARAMS %d" % len(params),
    "#define CB_NY %d" % len(names),
]
if "CB_In_t" in params:
    lines += ["#define CB_HAS_FLIGHT 1", "#define CB_NMAX %d" % params["CB_In_t"]]
lines.append("static const cb_param_t cb_params[CB_NPARAMS] = {")
for name, n in params.items():
    addr = name if n > 1 else "&" + name
    lines.append('    {"%s", %s, %d},' % (name, addr, n))
lines.append("};")
lines.append('const char *cb_out_names = "%s";' % " ".join(names))
lines.append("#endif")
pathlib.Path(out_header).write_text("\n".join(lines) + "\n")
print("gen_param_table: %d parameters, %d outputs -> %s" % (len(params), len(names), out_header))
